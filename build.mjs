/**
 * Build the browser half into the dsh client module format.
 *
 *   bun build.mjs
 *
 * src/entry.ts and the vendored ascii-sharks engine are bundled to CJS with
 * `react` left external (the page module table provides it), then wrapped in
 * the `window.__ModuleLoader__` factory every dsh client bundle registers.
 */
import { readFile, writeFile } from "node:fs/promises";

const PKG = "dsh-ascii-sharks";
const ENTRY = "./src/entry.ts";

const result = await Bun.build({
  entrypoints: [ENTRY],
  format: "cjs",
  target: "browser",
  external: ["react"],
  minify: false,
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

const body = await result.outputs[0].text();
const pkg = JSON.parse(await readFile("./package.json", "utf8"));

const banner = `/**
 * ${pkg.name} ${pkg.version} — generated by build.mjs, do not edit by hand.
 * ASCII Sharks engine: https://github.com/stackedlol/ascii-sharks (MIT).
 */
`;

const wrapped = `${banner}window.__ModuleLoader__.load({
\tid: ${JSON.stringify(PKG)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${body
  .split("\n")
  .map((line) => (line.length > 0 ? `\t\t${line}` : line))
  .join("\n")}
\t\treturn module.exports;
\t},
});
`;

await writeFile("./client.js", wrapped);
console.log(`client.js ${(wrapped.length / 1024).toFixed(1)} KiB`);
